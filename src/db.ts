import postgres from "postgres"

import type {
  ChangeEvent,
  ChangeRecord,
  ChangeStatus,
  NewNote,
  NewTicket,
  TicketNote,
  TicketPatch,
  TicketRecord,
  TicketStatus,
  TicketStore,
} from "./types.ts"

export const SCHEMA_SQL = `
CREATE TABLE IF NOT EXISTS tickets (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  number INTEGER GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  title TEXT NOT NULL,
  severity TEXT NOT NULL,
  category TEXT NOT NULL,
  status TEXT NOT NULL,
  source TEXT NOT NULL,
  requester_name TEXT NOT NULL,
  requester_email TEXT NOT NULL DEFAULT '',
  assignee_email TEXT,
  site_name TEXT,
  site_id TEXT,
  asset_tag TEXT,
  asset_id TEXT,
  device_id TEXT,
  device_name TEXT,
  lockhaven_alert_id TEXT,
  lockhaven_session_id TEXT,
  lockhaven_access_request_id TEXT,
  recording_url TEXT,
  session_reason TEXT,
  notes TEXT NOT NULL DEFAULT '',
  time_spent_minutes INTEGER NOT NULL DEFAULT 0,
  resolution TEXT,
  created_by_sub TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  resolved_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS tickets_alert_id_uidx
  ON tickets (lockhaven_alert_id)
  WHERE lockhaven_alert_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS tickets_session_id_uidx
  ON tickets (lockhaven_session_id)
  WHERE lockhaven_session_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS tickets_access_request_id_uidx
  ON tickets (lockhaven_access_request_id)
  WHERE lockhaven_access_request_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS ticket_notes (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_id UUID NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
  author_email TEXT NOT NULL DEFAULT '',
  author_name TEXT NOT NULL,
  body TEXT NOT NULL,
  minutes INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS changes (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  number INTEGER GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  title TEXT NOT NULL,
  summary TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL,
  requested_by_email TEXT NOT NULL,
  requested_by_name TEXT NOT NULL,
  approved_by_email TEXT,
  approved_at TIMESTAMPTZ,
  lockhaven_access_request_id TEXT,
  rollback_plan TEXT NOT NULL DEFAULT '',
  applied_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS change_events (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  change_id UUID NOT NULL REFERENCES changes(id) ON DELETE CASCADE,
  actor_email TEXT NOT NULL,
  actor_name TEXT NOT NULL,
  action TEXT NOT NULL,
  detail JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ingest_events (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  source TEXT NOT NULL,
  event TEXT NOT NULL,
  ticket_id UUID REFERENCES tickets(id) ON DELETE SET NULL,
  payload JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
`

type Sql = ReturnType<typeof postgres>

export function createSql(databaseUrl: string) {
  return postgres(databaseUrl, { max: 10, idle_timeout: 20 })
}

export async function migrate(sql: Sql) {
  await sql.unsafe(SCHEMA_SQL)
}

function mapTicket(row: Record<string, unknown>): TicketRecord {
  return {
    id: String(row.id),
    number: Number(row.number),
    title: String(row.title),
    severity: row.severity as TicketRecord["severity"],
    category: row.category as TicketRecord["category"],
    status: row.status as TicketRecord["status"],
    source: row.source as TicketRecord["source"],
    requesterName: String(row.requester_name),
    requesterEmail: String(row.requester_email),
    assigneeEmail: row.assignee_email ? String(row.assignee_email) : null,
    siteName: row.site_name ? String(row.site_name) : null,
    siteId: row.site_id ? String(row.site_id) : null,
    assetTag: row.asset_tag ? String(row.asset_tag) : null,
    assetId: row.asset_id ? String(row.asset_id) : null,
    deviceId: row.device_id ? String(row.device_id) : null,
    deviceName: row.device_name ? String(row.device_name) : null,
    lockhavenAlertId: row.lockhaven_alert_id
      ? String(row.lockhaven_alert_id)
      : null,
    lockhavenSessionId: row.lockhaven_session_id
      ? String(row.lockhaven_session_id)
      : null,
    lockhavenAccessRequestId: row.lockhaven_access_request_id
      ? String(row.lockhaven_access_request_id)
      : null,
    recordingUrl: row.recording_url ? String(row.recording_url) : null,
    sessionReason: row.session_reason ? String(row.session_reason) : null,
    notes: String(row.notes ?? ""),
    timeSpentMinutes: Number(row.time_spent_minutes ?? 0),
    resolution: row.resolution ? String(row.resolution) : null,
    createdBySub: row.created_by_sub ? String(row.created_by_sub) : null,
    createdAt: new Date(String(row.created_at)),
    updatedAt: new Date(String(row.updated_at)),
    resolvedAt: row.resolved_at ? new Date(String(row.resolved_at)) : null,
  }
}

