export function createTicketStore(sql: Sql): TicketStore & {
  listTickets(filter: {
    status?: TicketStatus | "all"
    q?: string
  }): Promise<TicketRecord[]>
  listNotes(ticketId: string): Promise<TicketNote[]>
  ping(): Promise<boolean>
} {
  return {
    async ping() {
      const rows = await sql`select 1 as ok`
      return rows.length === 1
    },
    async findById(id) {
      const rows = await sql`select * from tickets where id = ${id} limit 1`
      return rows[0] ? mapTicket(rows[0] as Record<string, unknown>) : null
    },
    async findByAlertId(alertId) {
      const rows =
        await sql`select * from tickets where lockhaven_alert_id = ${alertId} limit 1`
      return rows[0] ? mapTicket(rows[0] as Record<string, unknown>) : null
    },
    async findByAccessRequestId(accessRequestId) {
      const rows =
        await sql`select * from tickets where lockhaven_access_request_id = ${accessRequestId} limit 1`
      return rows[0] ? mapTicket(rows[0] as Record<string, unknown>) : null
    },
    async findBySessionId(sessionId) {
      const rows =
        await sql`select * from tickets where lockhaven_session_id = ${sessionId} limit 1`
      return rows[0] ? mapTicket(rows[0] as Record<string, unknown>) : null
    },
    async create(input: NewTicket) {
      const rows = await sql`
        insert into tickets (
          title, severity, category, status, source,
          requester_name, requester_email, assignee_email,
          site_name, site_id, asset_tag, asset_id, device_id, device_name,
          lockhaven_alert_id, lockhaven_session_id, lockhaven_access_request_id,
          recording_url, session_reason, notes, time_spent_minutes, resolution,
          created_by_sub, resolved_at
        ) values (
          ${input.title}, ${input.severity}, ${input.category},
          ${input.status ?? "open"}, ${input.source},
          ${input.requesterName}, ${input.requesterEmail},
          ${input.assigneeEmail ?? null},
          ${input.siteName ?? null}, ${input.siteId ?? null},
          ${input.assetTag ?? null}, ${input.assetId ?? null},
          ${input.deviceId ?? null}, ${input.deviceName ?? null},
          ${input.lockhavenAlertId ?? null}, ${input.lockhavenSessionId ?? null},
          ${input.lockhavenAccessRequestId ?? null},
          ${input.recordingUrl ?? null}, ${input.sessionReason ?? null},
          ${input.notes ?? ""}, ${input.timeSpentMinutes ?? 0},
          ${input.resolution ?? null}, ${input.createdBySub ?? null},
          ${input.resolvedAt ?? null}
        )
        returning *
      `
      return mapTicket(rows[0] as Record<string, unknown>)
    },
    async update(id, patch: TicketPatch) {
      const rows = await sql`
        update tickets set
          title = coalesce(${patch.title ?? null}, title),
          severity = coalesce(${patch.severity ?? null}, severity),
          category = coalesce(${patch.category ?? null}, category),
          status = coalesce(${patch.status ?? null}, status),
          assignee_email = coalesce(${patch.assigneeEmail ?? null}, assignee_email),
          notes = coalesce(${patch.notes ?? null}, notes),
          time_spent_minutes = coalesce(${patch.timeSpentMinutes ?? null}, time_spent_minutes),
          resolution = case
            when ${patch.resolution === null} then null
            else coalesce(${patch.resolution ?? null}, resolution)
          end,
          resolved_at = case
            when ${patch.resolvedAt === null} then null
            else coalesce(${patch.resolvedAt ?? null}, resolved_at)
          end,
          updated_at = now()
        where id = ${id}
        returning *
      `
      if (!rows[0]) {
        throw new Error("ticket not found")
      }
      return mapTicket(rows[0] as Record<string, unknown>)
    },
    async addNote(ticketId, note: NewNote) {
      const minutes = note.minutes ?? 0
      const rows = await sql`
        insert into ticket_notes (ticket_id, author_email, author_name, body, minutes)
        values (${ticketId}, ${note.authorEmail}, ${note.authorName}, ${note.body}, ${minutes})
        returning *
      `
      if (minutes > 0) {
        await sql`
          update tickets
          set time_spent_minutes = time_spent_minutes + ${minutes},
              updated_at = now()
          where id = ${ticketId}
        `
      } else {
        await sql`update tickets set updated_at = now() where id = ${ticketId}`
      }
      return mapNote(rows[0] as Record<string, unknown>)
    },
    async listTickets(filter) {
      const status = filter.status && filter.status !== "all" ? filter.status : null
      const q = filter.q?.trim() ? `%${filter.q.trim()}%` : null
      const rows = await sql`
        select * from tickets
        where (${status}::text is null or status = ${status})
          and (
            ${q}::text is null
            or title ilike ${q}
            or requester_name ilike ${q}
            or asset_tag ilike ${q}
            or device_name ilike ${q}
            or site_name ilike ${q}
          )
        order by
          case severity
            when 'critical' then 0
            when 'high' then 1
            when 'medium' then 2
            else 3
          end,
          updated_at desc
        limit 200
      `
      return rows.map((row) => mapTicket(row as Record<string, unknown>))
    },
    async listNotes(ticketId) {
      const rows =
        await sql`select * from ticket_notes where ticket_id = ${ticketId} order by created_at asc`
      return rows.map((row) => mapNote(row as Record<string, unknown>))
    },
  }
}

export async function createChange(
  sql: Sql,
  input: {
    title: string
    summary: string
    rollbackPlan: string
    requestedByEmail: string
    requestedByName: string
    lockhavenAccessRequestId?: string | null
  }
) {
  const rows = await sql`
    insert into changes (
      title, summary, status, requested_by_email, requested_by_name,
      lockhaven_access_request_id, rollback_plan
    ) values (
      ${input.title}, ${input.summary}, 'draft',
      ${input.requestedByEmail}, ${input.requestedByName},
      ${input.lockhavenAccessRequestId ?? null}, ${input.rollbackPlan}
    )
    returning *
  `
  const change = mapChange(rows[0] as Record<string, unknown>)
  await sql`
    insert into change_events (change_id, actor_email, actor_name, action, detail)
    values (
      ${change.id}, ${input.requestedByEmail}, ${input.requestedByName},
      'created', ${sql.json({ status: "draft" })}
    )
  `
  return change
}

export async function getChange(sql: Sql, id: string) {
  const rows = await sql`select * from changes where id = ${id} limit 1`
  return rows[0] ? mapChange(rows[0] as Record<string, unknown>) : null
}

export async function listChanges(sql: Sql) {
  const rows = await sql`select * from changes order by updated_at desc limit 200`
  return rows.map((row) => mapChange(row as Record<string, unknown>))
}

export async function listChangeEvents(sql: Sql, changeId: string) {
  const rows =
    await sql`select * from change_events where change_id = ${changeId} order by created_at asc`
  return rows.map((row) => mapChangeEvent(row as Record<string, unknown>))
}

export async function saveChangeTransition(
  sql: Sql,
  input: {
    id: string
    status: ChangeStatus
    approvedByEmail: string | null
    approvedAt: Date | null
    appliedAt: Date | null
    actorEmail: string
    actorName: string
    action: string
    detail: Record<string, unknown>
  }
) {
  const rows = await sql`
    update changes set
      status = ${input.status},
      approved_by_email = coalesce(${input.approvedByEmail}, approved_by_email),
      approved_at = coalesce(${input.approvedAt}, approved_at),
      applied_at = coalesce(${input.appliedAt}, applied_at),
      updated_at = now()
    where id = ${input.id}
    returning *
  `
  await sql`
    insert into change_events (change_id, actor_email, actor_name, action, detail)
    values (
      ${input.id}, ${input.actorEmail}, ${input.actorName},
      ${input.action}, ${sql.json(JSON.parse(JSON.stringify(input.detail)))}
    )
  `
  return mapChange(rows[0] as Record<string, unknown>)
}

export async function recordIngest(
  sql: Sql,
  input: {
    source: string
    event: string
    ticketId: string | null
    payload: unknown
  }
) {
  await sql`
    insert into ingest_events (source, event, ticket_id, payload)
    values (
      ${input.source}, ${input.event}, ${input.ticketId},
      ${sql.json(JSON.parse(JSON.stringify(input.payload)))}
    )
  `
}
